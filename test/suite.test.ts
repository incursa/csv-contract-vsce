test("collect-all and fail-fast distinguish assertion failure, execution error, skipped and no-target", async (t) => {
  const { master } = await fixture(t);
  const suite = await loadSuite(master, fileSuiteIO);
  const assertion = await runSuite(suite, async (c) => validateCsv(c, "Id\ninvalid\n"));
  assert.equal(assertion.exitCode, 1);
  assert.equal(assertion.valid, false);
  let calls = 0;
  const runner = async (c: CsvContract) => { if (++calls === 1) throw new Error("synthetic execution error"); return validateCsv(c, "Department\nIT\n"); };
  const all = await runSuite(suite, runner);
  assert.deepEqual(all.runs.map((r) => r.status), ["ERROR", "PASS"]);
  assert.equal(all.exitCode, 2);
  calls = 0;
  const fast = await runSuite(suite, runner, true);
  assert.deepEqual(fast.runs.map((r) => r.status), ["ERROR", "SKIPPED"]);
  assert.equal(calls, 1);
  delete suite.members[0].contract!.sqlServer;
  const missing = await runSuite(suite, runner);
  assert.equal(missing.runs[0].status, "ERROR");
});
test("external paths retain meaning after relocation and are reported as nonportable", async (t) => {
  const { root, master } = await fixture(t);
  const c = contract(); c.targets = [{ path: "../data/people.csv" }];
  await writeFile(join(root, "contracts", "a.yaml"), stringify(c));
  await mkdir(join(root, "moved"));
  const output = join(root, "moved", "bundle.yaml");
  await assert.rejects(combineSuite(master, output), /not portable/);
  const result = await combineSuite(master, output, { allowExternal: true });
  assert.equal(result.portable, false);
  const inline = parseSuite(await readFile(output, "utf8"));
  assert.equal(resolve(root, "moved", inline.members[0].contract!.targets![0].path!), resolve(root, "data/people.csv"));
  const split = await splitSuite(output, join(root, "elsewhere"));
  const restored = await loadSuite(split.master, fileSuiteIO);
  assert.equal(resolve(root, "elsewhere", restored.members[0].contract!.targets![0].path!), resolve(root, "data/people.csv"));
});
