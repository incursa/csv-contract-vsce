test("target baseline dependencies retain relative meaning through combine and split", async (t) => {
  const { root, master } = await fixture(t);
  const baseline = { baselineVersion: 1, revision: 1, capturedAt: "2026-09-11T00:00:00Z", sourceKind: "sql", captureMethod: "sql-metadata", columns: [{ name: "Id", ordinal: 1, collation: "Latin1_General_100_BIN2", uniqueKeys: '[{"name":"PK_Test","ordinal":1}]' }] };
  await writeFile(join(root, "schema.yaml"), stringify(baseline));
  const c = contract(); c.sqlServer = { targets: [{ connection: "test", schema: "dbo", table: "A", baseline: { ref: "../schema.yaml" } }] };
  await writeFile(join(root, "contracts", "a.yaml"), stringify(c));
  const bundle = join(root, "portable.yaml");
  await combineSuite(master, bundle, { allowExternal: true });
  const portable = await loadSuite(bundle, fileSuiteIO);
  assert.deepEqual(baselineReferences(portable.members[0].contract!), ["schema.yaml"]);
  const resolved = await resolveBaseline(portable.members[0].contract!, bundle, fileSuiteIO);
  assert.deepEqual(resolved.sqlServer?.targets?.[0].baseline, baseline);
  const executionTarget = await resolveTargetBaseline(portable.members[0].contract!.sqlServer!.targets![0], bundle, fileSuiteIO);
  assert.deepEqual(executionTarget.baseline, baseline);
  const split = await splitSuite(bundle, join(root, "split"));
  const reloaded = await loadSuite(split.master, fileSuiteIO);
  const again = await resolveBaseline(reloaded.members[0].contract!, reloaded.members[0].source, fileSuiteIO);
  assert.deepEqual(again.sqlServer?.targets?.[0].baseline, baseline);
});

const contract = (table = "Employees"): CsvContract => ({ version: 1, schema: { columns: { Id: { presence: "required", constraints: { allowedValues: ["001", "NULL", "true"] } } } }, sqlServer: { connection: "test", schema: "dbo", table } });
async function fixture(t: { after(fn: () => Promise<void>): void }) {
  const root = await mkdtemp(join(tmpdir(), "contract-suite-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  await mkdir(join(root, "contracts"));
  await writeFile(join(root, "contracts", "a.yaml"), "# Contract comment\n" + stringify(contract()));
  await writeFile(join(root, "contracts", "b.yaml"), stringify({ ...contract("Departments"), schema: { columns: { Department: { presence: "required" } } } }));
  const master = join(root, "master.csvsuite.yaml");
  await writeFile(master, stringify({ suiteVersion: 1, id: "hcm", metadata: { revision: "001" }, members: [{ id: "employees", ref: "./contracts/a.yaml" }, { id: "departments", ref: "./contracts/b.yaml" }] }));
  return { root, master };
}
test("combine/split preserves heterogeneous contracts, metadata, literals, order, comments and generated checks", async (t) => {
  const { root, master } = await fixture(t);
  const bundle = join(root, "portable.csvsuite.yaml");
  assert.equal((await combineSuite(master, bundle)).portable, true);
  const referenced = await loadSuite(master, fileSuiteIO);
  const portable = await loadSuite(bundle, fileSuiteIO);
  assert.deepEqual(portable.members.map((m) => m.contract), referenced.members.map((m) => m.contract));
  assert.deepEqual(generateSuiteSql(portable), generateSuiteSql(referenced));
  assert.match(await readFile(bundle, "utf8"), /Contract comment/);
  const split = await splitSuite(bundle, join(root, "split"));
  const restored = await loadSuite(split.master, fileSuiteIO);
  assert.deepEqual(restored.members.map((m) => m.contract), referenced.members.map((m) => m.contract));
  assert.equal(parseSuite(await readFile(split.master, "utf8")).metadata?.revision, "001");
  await assert.rejects(combineSuite(master, bundle), /overwrite/);
  await assert.rejects(splitSuite(bundle, join(root, "split")), /overwrite/);
  await combineSuite(master, bundle, { force: true });
  const sql = generateSuiteSql(portable);
  assert.equal(sql.batches.length, 2);
  assert.equal(sql.sql.match(/^GO$/gm)?.length, 2);
  assert.doesNotMatch(sql.sql, /t\.\*/);
});
test("connection defaults are atomic and target overrides contract overrides suite", () => {
  const c = contract();
  c.sqlServer = { schema: "dbo", table: "A" };
  assert.equal(effectiveContract(c, { connection: "shared" }).sqlServer?.connection, "shared");
  c.sqlServer = { connection: "member", targets: [{ schema: "dbo", table: "A" }, { schema: "dbo", table: "B", integratedConnection: { server: "local", database: "test" } }] };
  const result = effectiveContract(c, { connection: "shared" });
  assert.equal(result.sqlServer?.targets?.[0].connection, "member");
  assert.equal(result.sqlServer?.targets?.[1].connection, undefined);
  assert.equal(result.sqlServer?.targets?.[1].integratedConnection?.database, "test");
  assert.equal(c.sqlServer.targets?.[0].connection, undefined);
});
