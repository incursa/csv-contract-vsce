test("SQL responses cannot silently omit or corrupt expected rules", () => {
  assert.throws(() => assertCompleteSqlSummaries(["a"], []), /expected rule/);
  assert.throws(() => assertCompleteSqlSummaries(["a"], [{ RuleId: "a", FailureCount: "NaN" }]), /Invalid/);
  assert.throws(() => assertCompleteSqlSummaries(["a"], [{ RuleId: "a", FailureCount: 0 }, { RuleId: "a", FailureCount: 0 }]), /unexpected/);
  assert.doesNotThrow(() => assertCompleteSqlSummaries(["a"], [{ RuleId: "a", FailureCount: "0" }]));
});
test("CLI returns execution-error JSON without connecting and CSV suites retain inline member identity", async (t) => {
  const { root, master } = await fixture(t);
  await rm(join(root, "contracts", "a.yaml"));
  await rm(join(root, "contracts", "b.yaml"));
  const cli = resolve("dist/cli/csv-contract.cjs");
  const bad = spawnSync(process.execPath, [cli, "dbtest", "--spec", master, "--format", "json"], { encoding: "utf8" });
  assert.equal(bad.status, 2, bad.stderr);
  const report = JSON.parse(bad.stdout);
  assert.equal(report.valid, false);
  assert.deepEqual(report.runs.map((r: { status: string }) => r.status), ["ERROR", "ERROR"]);
  const c = contract(); delete c.sqlServer; c.targets = [{ path: "./input.csv" }];
  await writeFile(join(root, "input.csv"), "Id\n001\n");
  await writeFile(master, stringify({ suiteVersion: 1, id: "files", members: [{ id: "one", contract: c }, { id: "two", contract: c }] }));
  const csv = spawnSync(process.execPath, [cli, "test", "--spec", master, "--format", "json"], { encoding: "utf8" });
  assert.equal(csv.status, 0, csv.stderr);
  const result = JSON.parse(csv.stdout);
  assert.equal(result.runs.length, 2);
  assert.equal(result.performance.passes, 1);
  assert.notEqual(result.runs[0].spec, result.runs[1].spec);
});
